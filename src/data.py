"""Data loading, validation, and a schema-identical synthetic fallback.

Real data: Kaggle "Store Item Demand Forecasting Challenge"
(`kaggle competitions download -c demand-forecasting-kernels-only`), file
`train.csv` with columns: date (daily), store (1-10), item (1-50), sales (int).

If that file is absent, `ensure_raw_data()` generates a synthetic train.csv with
the identical schema so the whole pipeline runs end-to-end. Swap in the real file
and re-run for real numbers — no code changes.
"""
from __future__ import annotations

from pathlib import Path

import numpy as np
import pandas as pd

from .utils import load_config, resolve, set_seed


def _cols(cfg: dict) -> tuple[str, str, str, str]:
    d = cfg["data"]
    return d["date_col"], d["store_col"], d["item_col"], d["target_col"]


def load_raw(cfg: dict | None = None) -> pd.DataFrame:
    """Load and validate the raw train.csv.

    Validations (per spec section 2):
      * parse `date` to datetime,
      * assert sales >= 0,
      * assert NO missing dates within each (store, item) series.
    """
    cfg = cfg or load_config()
    date_c, store_c, item_c, target_c = _cols(cfg)
    raw_path = resolve(cfg["paths"]["raw_csv"])
    if not raw_path.exists():
        raise FileNotFoundError(
            f"{raw_path} not found. Run `ensure_raw_data()` or download the "
            f"Kaggle dataset (see README)."
        )

    df = pd.read_csv(raw_path, parse_dates=[date_c])
    df = df.sort_values([store_c, item_c, date_c]).reset_index(drop=True)

    # sales >= 0
    if (df[target_c] < 0).any():
        raise ValueError("Found negative sales values; expected sales >= 0.")

    # No missing dates per (store, item): span length must equal row count.
    def _check_contiguous(g: pd.DataFrame) -> bool:
        span = (g[date_c].max() - g[date_c].min()).days + 1
        return span == len(g) and g[date_c].is_unique

    ok = df.groupby([store_c, item_c], observed=True).apply(
        _check_contiguous, include_groups=False
    )
    if not ok.all():
        bad = ok[~ok].index.tolist()[:5]
        raise ValueError(f"Missing/duplicate dates in series (first few): {bad}")

    return df


def make_synthetic(cfg: dict | None = None) -> pd.DataFrame:
    """Generate a synthetic dataset mirroring the Kaggle schema and structure.

    Structure per series = base level (store & item scaled) x yearly seasonality
    x weekly pattern x mild upward trend + Poisson noise. This gives baselines and
    XGBoost something real to model, so the results table is meaningful.
    """
    cfg = cfg or load_config()
    set_seed(cfg.get("seed", 42))
    s = cfg["synthetic"]
    date_c, store_c, item_c, target_c = _cols(cfg)

    dates = pd.date_range(s["start"], s["end"], freq="D")
    doy = dates.dayofyear.to_numpy()
    dow = dates.dayofweek.to_numpy()
    t = np.arange(len(dates))

    yearly = 1.0 + 0.30 * np.sin(2 * np.pi * (doy - 80) / 365.25)   # peak ~spring
    weekly = 1.0 + 0.20 * (dow >= 5)                                 # weekend lift
    trend = 1.0 + 0.15 * (t / len(dates))                           # +15% over span

    rng = np.random.default_rng(cfg.get("seed", 42))
    frames = []
    for store in range(1, s["n_stores"] + 1):
        store_mult = 0.7 + 0.06 * store                            # store size
        for item in range(1, s["n_items"] + 1):
            item_base = 5 + (item % 25)                            # item popularity
            mean = item_base * store_mult * yearly * weekly * trend
            sales = rng.poisson(np.clip(mean, 0.1, None)).astype(int)
            frames.append(
                pd.DataFrame(
                    {date_c: dates, store_c: store, item_c: item, target_c: sales}
                )
            )
    df = pd.concat(frames, ignore_index=True)
    return df.sort_values([store_c, item_c, date_c]).reset_index(drop=True)


def ensure_raw_data(cfg: dict | None = None) -> Path:
    """Guarantee data/raw/train.csv exists; synthesize it if missing (and enabled)."""
    cfg = cfg or load_config()
    raw_path = resolve(cfg["paths"]["raw_csv"])
    if raw_path.exists():
        return raw_path
    if not cfg.get("synthetic", {}).get("enabled", False):
        raise FileNotFoundError(
            f"{raw_path} missing and synthetic fallback disabled. Download the "
            f"Kaggle dataset (see README)."
        )
    raw_path.parent.mkdir(parents=True, exist_ok=True)
    df = make_synthetic(cfg)
    df.to_csv(raw_path, index=False)
    # Marker so reports can honestly label numbers as synthetic. Delete this file
    # after downloading the real Kaggle train.csv (see README).
    (raw_path.parent / ".synthetic").touch()
    return raw_path


def data_is_synthetic(cfg: dict | None = None) -> bool:
    """True when the current train.csv was generated by us (labelling only)."""
    cfg = cfg or load_config()
    return (resolve(cfg["paths"]["raw_csv"]).parent / ".synthetic").exists()


if __name__ == "__main__":  # manual smoke check
    cfg = load_config()
    path = ensure_raw_data(cfg)
    df = load_raw(cfg)
    print(f"raw rows={len(df):,} series={df[['store','item']].drop_duplicates().shape[0]} "
          f"dates {df['date'].min().date()}..{df['date'].max().date()} file={path}")
